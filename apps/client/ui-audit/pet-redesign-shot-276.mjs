import { spawn } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const __dirname = dirname(fileURLToPath(import.meta.url));
const CLIENT_DIR = join(__dirname, "..");
const PORT = 5194;
const BASE_URL = `http://localhost:${PORT}`;
const OUT_DIR = "C:\\Users\\MSchu\\AppData\\Local\\Temp\\claude\\G--GameDev\\553d2095-3a73-4795-9782-0fe746a25f13\\scratchpad";

function startDevServer() {
  const viteBin = join(CLIENT_DIR, "node_modules", "vite", "bin", "vite.js");
  const child = spawn(
    process.execPath,
    [viteBin, "dev", "--config", join(__dirname, "vite.tour.config.mjs"), "--port", String(PORT), "--strictPort"],
    { cwd: CLIENT_DIR, stdio: ["ignore", "pipe", "pipe"] },
  );
  let out = "";
  child.stdout.on("data", (d) => (out += d.toString()));
  child.stderr.on("data", (d) => (out += d.toString()));
  return { child, getOutput: () => out };
}

async function waitForServer(url, t = 40000) {
  const s = Date.now();
  while (Date.now() - s < t) {
    try { const r = await fetch(url); if (r.ok) return true; } catch {}
    await new Promise((r) => setTimeout(r, 300));
  }
  return false;
}

async function clickWithReloadRetry(page, locator, opts = {}) {
  try {
    await locator.click({ timeout: 6000, ...opts });
  } catch {
    await page.waitForTimeout(400);
    await locator.click({ timeout: 6000, ...opts });
  }
}

const { child, getOutput } = startDevServer();
try {
  const ok = await waitForServer(BASE_URL);
  if (!ok) { console.error("SERVER NOT UP:\n" + getOutput()); process.exit(1); }
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
  page.on("console", (m) => { if (m.type() === "error") errors.push("console: " + m.text()); });

  await page.goto(`${BASE_URL}/?fixture=pettest`, { waitUntil: "load" });
  await page.waitForSelector('[data-guide-id^="sidebar."]', { timeout: 15000 });
  await page.waitForTimeout(4500); // let load-toasts clear

  // ── 1) Companions page ──
  await clickWithReloadRetry(page, page.locator('[data-guide-id="topbar.companions"]').first());
  await page.waitForTimeout(600);
  await page.screenshot({ path: join(OUT_DIR, "pet-redesign-companions-1920.png"), fullPage: true });
  console.log("SHOT SAVED: pet-redesign-companions-1920.png");
  // The gallery scrolls inside an inner container, not the document body — fullPage only captures
  // the first viewport, and a plain element screenshot of `.pet-gallery-grid` came back mostly
  // blank below row 1 (rows below the fold apparently don't have real layout until scrolled into
  // view). Find the actual scrolling ancestor and step through it, screenshotting each viewport —
  // this is the 21-pet gallery (6 rows of 4), so 2 more scroll steps cover the 6 new #276 kinds
  // (vellumoth/gorehound/ironmaw/carapace/carrionwing/charnel are pets #14-21).
  const scrollerHandle = await page.evaluateHandle(() => {
    const grid = document.querySelector(".pet-gallery-grid");
    let el = grid;
    while (el && el !== document.body) {
      const cs = getComputedStyle(el);
      if ((cs.overflowY === "auto" || cs.overflowY === "scroll") && el.scrollHeight > el.clientHeight + 4) return el;
      el = el.parentElement;
    }
    return document.scrollingElement;
  });
  for (let step = 1; step <= 5; step++) {
    await scrollerHandle.evaluate((el, s) => el.scrollBy(0, s), 900);
    await page.waitForTimeout(400);
    await page.screenshot({ path: join(OUT_DIR, `pet-redesign-companions-scroll${step}-1920.png`), fullPage: false });
    console.log(`SHOT SAVED: pet-redesign-companions-scroll${step}-1920.png`);
  }

  // ── 2) Companion picker dropdown open ──
  await clickWithReloadRetry(page, page.locator(".pet-slot-btn").first());
  await page.waitForTimeout(300);
  await page.screenshot({ path: join(OUT_DIR, "pet-redesign-picker-1920.png"), fullPage: false });
  console.log("SHOT SAVED: pet-redesign-picker-1920.png");
  await page.locator(".pet-slot-btn").first().click(); // close dropdown

  // ── 3) Combat log with ability display name ──
  await clickWithReloadRetry(page, page.locator('[data-guide-id="sidebar.combat"]').first());
  await page.waitForTimeout(500);
  // "The Highlands" / "Das Hochland" — home of void_titan (358 maxHp, the tankiest non-slayer-gated
  // monster in the catalog). A tanky enough monster keeps a SINGLE encounter alive past gemwraith's
  // 4.5s ability interval. KILL_COOLDOWN_MS (2s) pauses the pet-ability timer between kills
  // (combat.ts), so a monster that dies in one hit never accumulates 4.5s of active time.
  await clickWithReloadRetry(page, page.locator(".zone-card", { hasText: /Highlands|Hochland/ }).first());
  await page.waitForTimeout(1500);
  const titanCard = page.locator(".monster-card", { hasText: /Void Titan|Leeren-Titan/i });
  await clickWithReloadRetry(page, (await titanCard.count()) > 0 ? titanCard.locator(".mc-fight-btn").first() : page.locator(".mc-fight-btn").last());
  // gemwraith combatAbility.intervalMs = 4500ms — wait well past a couple of triggers.
  await page.waitForTimeout(18000);
  await page.screenshot({ path: join(OUT_DIR, "pet-redesign-combat-1920.png"), fullPage: false });
  console.log("SHOT SAVED: pet-redesign-combat-1920.png");
  try {
    const log = page.locator(".battle-log, .combat-log").first();
    await log.screenshot({ path: join(OUT_DIR, "pet-redesign-combat-log-crop.png") });
    console.log("SHOT SAVED: pet-redesign-combat-log-crop.png");
  } catch (e) {
    console.log("!! log closeup failed: " + e.message);
  }

  // ── 4) Shop sell price with vellumoth (sellBonus) active ──
  await clickWithReloadRetry(page, page.locator('[data-guide-id="sidebar.combat"]').first());
  await page.waitForTimeout(300);
  await clickWithReloadRetry(page, page.locator('[data-guide-id="topbar.companions"]').first());
  await page.waitForTimeout(400);
  await clickWithReloadRetry(page, page.locator(".pet-slot-btn").first());
  await page.waitForTimeout(300);
  // vellumoth's DE name is "Pergamotte" (content.pets.vellumoth.name.de) — fixture defaults to DE.
  await clickWithReloadRetry(page, page.locator(".pet-select-entry", { hasText: /vellumoth|Pergamotte/i }).first());
  await page.waitForTimeout(300);
  await clickWithReloadRetry(page, page.locator('[data-guide-id="topbar.shop"]').first());
  await page.waitForTimeout(500);
  await clickWithReloadRetry(page, page.locator(".shopv2-maintab").nth(1)); // Sell tab
  await page.waitForTimeout(400);
  const sellCells = page.locator(".shopv2-sell-cell");
  if ((await sellCells.count()) > 0) {
    await sellCells.first().click();
    await page.waitForTimeout(300);
    await page.screenshot({ path: join(OUT_DIR, "pet-redesign-shop-sell-vellumoth-1920.png"), fullPage: false });
    console.log("SHOT SAVED: pet-redesign-shop-sell-vellumoth-1920.png");
  } else {
    console.log("!! no sell cells found");
  }

  console.log(errors.length ? "PAGE ERRORS:\n" + errors.slice(0, 20).join("\n") : "no page errors");
  await browser.close();
} finally {
  child.kill();
}
